-- The caller supplies a disposable spot within reach of the connected client.
return function(player, check, pos)
	local inv = player:get_inventory()
	local saved = inv:get_list("main")
	inv:set_list("main", {})
	local st = bc.state(player)
	local floor = vector.offset(pos, 0, -1, 0)
	core.set_node(floor, {name = "bc:dirt_grass"})
	local function use()
		local node = core.get_node(pos)
		return core.registered_nodes[node.name].on_rightclick(pos, node, player, player:get_wielded_item())
	end

	core.set_node(pos, {name = "bc:nurse_log", param2 = 3})
	use()
	check(inv:contains_item("main", "bc:worm") and st.p.notes.nurse_log, "turning a log did not reveal worms")
	check(core.get_node(pos).name == "bc:nurse_log_turned", "log still offers another harvest")
	local wait = core.registered_nodes["bc:nurse_log_turned"].on_timer
	check(wait(pos), "log refreshed before the colony returned")
	core.get_meta(pos):set_float("ready", bc.clock - 1)
	wait(pos)
	check(core.get_node(pos).name == "bc:nurse_log" and core.get_node(pos).param2 == 3, "log did not recover in place")
	player:set_wielded_item(ItemStack("bc:sharp_stone"))
	use()
	check(inv:contains_item("main", "bc:tinder_conk 2") and st.p.notes.bracket_tinder, "knife did not cut bracket tinder")

	core.set_node(pos, {name = "bc:bush_red_ripe"})
	use()
	local wear = player:get_wielded_item():get_wear()
	local fruit_due = core.get_meta(pos):get_float("fruit_after")
	use()
	use()
	check(inv:contains_item("main", "bc:bush_red_cutting") and not inv:contains_item("main", "bc:bush_red_cutting 2"),
		"the same growth should give exactly one cutting")
	check(player:get_wielded_item():get_wear() > wear and st.p.notes.berry_cuttings, "pruning used no knife or missed the note")
	check(math.abs(core.get_meta(pos):get_float("fruit_after") - fruit_due - 18) < 0.01,
		"pruning did not delay the existing crop")
	core.remove_node(pos)
	local cutting = inv:remove_item("main", "bc:bush_red_cutting")
	local pt = {type = "node", under = floor, above = pos}
	local planted = core.registered_nodes["bc:bush_red_cutting"].on_place(cutting, player, pt)
	check(planted:is_empty() and core.get_node(pos).name == "bc:bush_red_cutting", "cutting did not take to soil")
	check(core.registered_nodes["bc:bush_red_cutting"].on_timer(pos), "a fresh cutting matured immediately")
	core.set_node(pos, {name = "bc:cactus"})
	local cactus = core.registered_nodes["bc:cactus"]
	check(cactus.on_timer(pos), "prickly pear fruited before its game-clock deadline")
	core.get_meta(pos):set_float("fruit_after", bc.clock - 1)
	cactus.on_timer(pos)
	check(core.get_node(pos).name == "bc:cactus_ripe", "prickly pear did not ripen after elapsed game time")

	core.set_node(pos, {name = "bc:snow"})
	local deer = bc.spawn_animal("deer", vector.offset(floor, 0, 0.5, 0))
	local animal = deer:get_luaentity()
	local dr = deer:get_pos()
	local previous = vector.offset(dr, 0, 0, -4)
	bc.leave_print(animal, dr, dr)
	check(not animal.prints, "animal with no movement left a trail")
	bc.leave_print(animal, previous, dr)
	if check(animal.prints and #animal.prints == 1, "moving deer left no track in snow") then
		local print = animal.prints[1]:get_luaentity()
		check(print.direction == "north" and print.life > 1.5, "snow track has incorrect bearing or lifetime")
		check(print.object:get_pos().y > floor.y + 0.75, "snow covers the track art")
		print:on_rightclick(player)
		check(st.p.notes.track_deer, "reading a deer track did not reach the journal")
		bc.leave_print(animal, previous, dr)
		check(#animal.prints == 1, "stationary deer stamped duplicate tracks")
		print.born = bc.clock - 3
		print:on_rightclick(player)
		check(not animal.prints[1]:get_pos() and core.get_node(pos).name == "bc:snow", "expiring prints changed the snow")
		animal.last_print = nil
		bc.leave_print(animal, previous, dr)
		print = animal.prints[#animal.prints]:get_luaentity()
		core.remove_node(pos)
		print:on_rightclick(player)
		check(not animal.prints[#animal.prints]:get_pos(), "track hovered after its snow was removed")
	end
	deer:remove()

	inv:set_list("main", {})
	core.set_node(pos, {name = "bc:water_source"})
	player:set_wielded_item(ItemStack("bc:fishing_rod"))
	inv:add_item("main", "bc:meat_raw")
	inv:add_item("main", "bc:meat_spoiled")
	inv:add_item("main", "bc:worm")
	local function cast()
		st.fish_at = nil
		bc.hunt.fish(player:get_wielded_item(), player, {type = "node", under = pos, above = vector.offset(pos, 0, 1, 0)})
	end
	cast()
	check(st.fishing.bait and st.fishing.bait:get_name() == "bc:worm", "rod spent meat with worms in the pack")
	cast()
	check(inv:contains_item("main", "bc:worm"), "uncaught bait lost when reeling in")
	inv:remove_item("main", "bc:worm")
	inv:remove_item("main", "bc:meat_spoiled")
	cast()
	check(st.fishing and not st.fishing.bait and inv:contains_item("main", "bc:meat_raw"), "rod spent fresh meat on an ordinary cast")
	cast()
	core.remove_node(pos)
	inv:set_list("main", saved)
end
